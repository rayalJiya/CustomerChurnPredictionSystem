from src.common import load_dataset, validate_dataset

df = load_dataset()
print("\n===== DATASET OVERVIEW =====")
print("File: customer-churn-dataset-testing-master.csv")
print("Rows and columns:", df.shape)
print("\n===== COLUMN NAMES =====")
print(df.columns.tolist())
print("\n===== DATA TYPES =====")
print(df.dtypes.to_string())
print("\n===== MISSING VALUES =====")
print(df.isna().sum().to_string())
print("\n===== DUPLICATE ROWS =====")
print(df.duplicated().sum())
print("\n===== FIRST 5 ROWS =====")
print(df.head().to_string(index=False))
print("\n===== UNIQUE VALUES IN EACH COLUMN =====")
for column in df.columns:
    print(f"{column}: {df[column].nunique(dropna=False)}")
print("\n===== TARGET COLUMN CHECK =====")
validate_dataset(df)
print("Target column: Churn")
print(df["Churn"].value_counts(dropna=False).sort_index().to_string())
print("\nTarget proportions:")
print((df["Churn"].value_counts(normalize=True).sort_index() * 100).round(2).astype(str).add("%").to_string())
print("\n===== NUMERIC SUMMARY =====")
print(df.describe().to_string())
